import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL("../database/prisma/schema.prisma", import.meta.url);
const destination = new URL("../database/prisma/production/schema.prisma", import.meta.url);
const local = readFileSync(source, "utf8");
if (!/provider\s*=\s*"sqlite"/.test(local)) throw new Error("Expected the canonical local SQLite schema");
const production = "// Generated by scripts/prepare-production-schema.mjs. Edit prisma/schema.prisma instead.\n" +
  local.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"').replace(/url\s*=\s*"file:\.\/dev\.db"/, 'url = env("DATABASE_URL")');

if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== production) {
    throw new Error("Production schema is stale. Run pnpm db:schema:prepare and add a reviewed PostgreSQL migration.");
  }
  console.log("Production schema matches the canonical data model.");
} else {
  mkdirSync(new URL("../database/prisma/production/", import.meta.url), { recursive: true });
  writeFileSync(destination, production);
  console.log(`Prepared ${fileURLToPath(destination)}`);
}
